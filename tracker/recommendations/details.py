"""§9.10's ``details:`` overrides — the *"Why"* line, said in nouns instead of adjectives.

    Why: unblocks Ice Barrage NH (+0.44) · cuts Train Magic 87 → 94 from 113h to 16h (+0.38)

:mod:`tracker.recommendations.reasons` sees a normalized factor value and nothing else, and
§9.5 requires that it stay that way: *"the 'Reason' line in the UI is then generated by
reading off the largest terms, rather than being separately authored prose that can drift
from the actual ranking."* So it can say *"unblocks several capabilities"* and never
*"unblocks Ice Barrage NH"*, because the name is not among the things it is allowed to know.

The sanctioned way through is the ``details:`` mapping, which lets the engine substitute a
phrase where it has context the reason module does not. This module is that substitution,
factored out of ``engine.py`` because it grew past the two lines it started as.

**Words only, never numbers.** The credit printed beside each phrase is computed from
:func:`~tracker.recommendations.reasons.headroom` in every case, substituted or not, so a
more specific phrase cannot flatter the factor it labels. That is the whole reason the
override replaces a string rather than a contribution.

Why ``pvp_value`` is never overridden
-------------------------------------

It is the tempting one and it is the one that would be a lie. A generated skill band carries
``advances: {}``, so its ``pvp_value`` is the ε floor and its credit is nearly zero — yet its
consequences may well name a capability it measurably advances. Writing *"works toward Boss
fundamentals (+0.02)"* would attach a goal to a factor that earned nothing, which is exactly
the flattery the seam's contract forbids, and it would do it in the one place a reader most
reasonably trusts the number.

*Works toward* is therefore a **display row** and not a reason phrase. The card says it; the
sentence that decomposes the ranking does not, because the ranking did not.
"""

from __future__ import annotations

from collections.abc import Sequence

from tracker.domain.types import Acceleration, Consequences, UnblockedCapability


def leverage_detail(unblocked: Sequence[UnblockedCapability], unlock_count: int) -> dict[str, str]:
    """§9.10's *"unblocks Ice Barrage NH"* — the names, where the names are known.

    Falls back to the count when no name resolves, which is the pre-existing behaviour and
    the honest one: the factor counted something, so *"unblocks 2 capabilities"* is still
    true even where the corpus can no longer say what they were called.

    One name is spelled out and the rest are summarized. A line naming four capabilities
    stops being read, and the leading one is the strongest by roadmap weight — the ordering
    :func:`~tracker.domain.consequences.unblocked_capabilities` inherited from the flip walk.
    """
    if unlock_count <= 0:
        return {}
    if not unblocked:
        noun = "capability" if unlock_count == 1 else "capabilities"
        return {"leverage": f"unblocks {unlock_count} {noun}"}
    first, *rest = unblocked
    if not rest:
        return {"leverage": f"unblocks {first.name}"}
    return {"leverage": f"unblocks {first.name} and {len(rest)} more"}


def method_unlock_detail(speeds_up: Sequence[Acceleration]) -> dict[str, str]:
    """A30's *"cuts Train Magic 87 → 94 from 113h to 16h"*.

    The two sizings rather than a percentage, because *"an 86% reduction"* is a fact about
    the factor and *"113h to 16h"* is a fact about the player's evening. Both come from the
    same argmax; only one of them answers *"should I do this first?"*.
    """
    if not speeds_up:
        return {}
    entry = speeds_up[0]
    return {
        "method_unlock": (
            f"cuts {entry.name} from {_hours(entry.hours_before)} to {_hours(entry.hours_after)}"
        )
    }


def progression_details(consequences: Consequences, unlock_count: int) -> dict[str, str]:
    """Every override a progression candidate earns, assembled.

    Deliberately not ``pvp_value`` — see the module docstring — and not ``proximity``, which
    belongs to refreshers alone (:func:`~tracker.recommendations.engine._urgency_phrase`).
    """
    return {
        **leverage_detail(consequences.unblocks_capabilities, unlock_count),
        **method_unlock_detail(consequences.speeds_up),
    }


def _hours(hours: float) -> str:
    """``113h``, or ``7.5h`` below ten.

    Whole hours read as an estimate, which is what §8 produces; a decimal on a three-figure
    number would imply a precision the sizing does not have. Under ten hours the decimal is
    the difference between two genuinely different evenings, so it is kept.
    """
    if hours < 10.0:
        return f"{hours:.1f}h"
    return f"{hours:.0f}h"
