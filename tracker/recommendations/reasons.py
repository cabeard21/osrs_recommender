"""§9.10's *"Why"* line, read off the numbers that produced the ranking.

    Why: high PvP value (+0.61) · unblocks 2 capabilities (+0.44) · close to target (+0.30)

§9.5 is explicit that this prose is **generated**, not authored: *"the 'Reason' line in the
UI is then generated by reading off the largest terms, rather than being separately authored
prose that can drift from the actual ranking."* Nothing here may therefore consult a
candidate's id, kind or name to decide what to say — everything it prints comes from
:class:`~tracker.domain.types.FactorContribution`, which is also what §6.10 persists. A
reason and its ranking are the same calculation rendered twice.

Headroom: why the displayed numbers are positive
------------------------------------------------

Log contributions are ``wᵢ · ln(fᵢ)`` with every ``fᵢ ≤ 1``, so every term is ``≤ 0`` — and
§9.10 shows *positive* credits. The two reconcile by measuring each term from the **floor**
rather than from a perfect score::

    headroom(f) = wᵢ · (ln(fᵢ) − ln(ε))

An affine transform of the log contribution: the same number, read from the bottom of the
scale instead of the top. It earns the transform for two reasons beyond the sign.

*It answers the question the line asks.* Ranked by raw log contribution, the "largest" term
is always whichever factor sits closest to 1.0 — so a candidate that happens to be free
would report *"cheap"* as its leading reason even when what won it the top slot was PvP
value. Headroom credits a factor for how far it beat the worst case, which is what
distinguishes this candidate from the ones below it.

*The parts sum to the whole.* ``Σ headroom = ln(score) − Σ wᵢ·ln(ε)``, a monotone function
of the score itself. Ordering candidates by total headroom is ordering them by score, so
the credits shown are a decomposition of the ranking rather than a commentary beside it.
"""

from __future__ import annotations

import math
from collections.abc import Mapping

from tracker.content.schema import ScoringProfile
from tracker.domain.types import FactorContribution

#: How many factors §9.10's example line names. Three fits a terminal line and a phone
#: card, and the fourth-largest credit has yet to be what changes anyone's mind.
_DEFAULT_TOP = 3

#: Below this much headroom a factor is not worth naming: it says the candidate is barely
#: better than the floor on that axis, which is not a reason to do it.
_MIN_HEADROOM = 0.01

#: Value thresholds → phrase, per factor, strongest first. Prose only; the number beside
#: each phrase comes from the arithmetic, so a mis-worded band can mislabel a credit but
#: can never change one.
_PHRASES: Mapping[str, tuple[tuple[float, str], ...]] = {
    "pvp_value": (
        (0.75, "high PvP value"),
        (0.40, "moderate PvP value"),
        (0.0, "some PvP value"),
    ),
    "leverage": (
        (0.75, "unblocks a great deal"),
        (0.40, "unblocks several capabilities"),
        (0.0, "unblocks something"),
    ),
    "proximity": (
        (0.75, "close to target"),
        (0.40, "part-way there"),
        (0.0, "early progress"),
    ),
    "effort_decay": (
        (0.75, "quick to finish"),
        (0.40, "a moderate time investment"),
        (0.0, "a long grind"),
    ),
    "cost_decay": (
        (0.75, "cheap"),
        (0.40, "affordable"),
        (0.0, "expensive"),
    ),
}


def headroom(contribution: FactorContribution, profile: ScoringProfile) -> float:
    """``wᵢ · (ln(fᵢ) − ln(ε))`` — one factor's credit above the floor.

    Never negative: a value at or below ε is floored, and a value above 1 cannot occur
    because every §9.4 factor is normalized to ``(0, 1]``. The ``max`` guards the first
    case, applying the floor in exactly the place the scorer applied it.
    """
    floored = max(contribution.value, profile.epsilon)
    return contribution.weight * (math.log(floored) - math.log(profile.epsilon))


def reason(
    factors: Mapping[str, FactorContribution],
    profile: ScoringProfile,
    *,
    top: int = _DEFAULT_TOP,
    details: Mapping[str, str] | None = None,
) -> str:
    """§9.10's *"Why"* line for one candidate.

    ``details`` lets the engine substitute a more specific phrase where it has context this
    module does not — *"unblocks 2 capabilities"* rather than *"unblocks several
    capabilities"*, since the count is known where the counting happened. It replaces only
    the words; the credit beside them is still the computed one, so a substituted phrase
    cannot flatter a factor.

    Returns an empty string when nothing clears :data:`_MIN_HEADROOM`. Silence is the honest
    output for a candidate barely above the floor on every axis — inventing a reason for it
    would be exactly the authored prose §9.5 forbids.
    """
    overrides = details or {}
    credits = [
        (name, headroom(contribution, profile), contribution)
        for name, contribution in factors.items()
    ]
    named = sorted(
        (entry for entry in credits if entry[1] >= _MIN_HEADROOM),
        key=lambda entry: (-entry[1], entry[0]),
    )[:top]

    return " · ".join(
        f"{overrides.get(name) or _phrase(name, contribution.value)} (+{credit:.2f})"
        for name, credit, contribution in named
    )


def _phrase(name: str, value: float) -> str:
    """The band description for one factor value, or the factor's own name if unmapped.

    An unmapped factor is one added to §9.4 without a phrase; naming it plainly keeps the
    line truthful and makes the omission visible, which a generic *"other"* would not.
    """
    for threshold, phrase in _PHRASES.get(name, ()):
        if value >= threshold:
            return phrase
    return name.replace("_", " ")
