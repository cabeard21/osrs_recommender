"""§9.4's weighted geometric mean, evaluated in log space (§9.5).

    score = Π fᵢ ^ wᵢ        ⟺        ln(score) = Σ wᵢ · ln(fᵢ)

The two forms are the same number, and §9.5 asks for the second because it turns each
factor's influence into an **additive term in shared units**. That is not a numerical
convenience: §9.10's *"Why"* line is generated by reading off the largest terms, so the
prose and the ranking come out of one calculation and cannot drift apart. Persisting the
terms is what makes the explanation auditable rather than decorative (§6.10).

Every factor is floored at ε before the logarithm (§9.4) — *"so no single term can
annihilate a score"*, and so ``ln(0)`` never happens. The floor belongs here rather than in
the derivations: a genuine zero is a real fact about a candidate (``train_woodcutting``
advances nothing, and says so), and flooring it at the source would hide that fact behind a
tuning constant. :func:`tracker.domain.candidates.leverage` makes the same argument from
the other side.

**The two unknown magnitudes.** §8 returns ``hours = None`` and ``gp = None`` for a
candidate it cannot size — a ``quest:`` candidate, whose duration the SDD authors nowhere.
Reading either absence as ``0`` gives ``exp(0) = 1.0``: a *perfect* mark on the axis we know
least about, which is A8's defect one candidate kind over. Both are instead charged one
scale unit — ``profile.unknown_effort_hours`` for time (default equal to τ) and κ itself for
cost — so an unsized candidate scores ``exp(−1) ≈ 0.37`` there. The charge is authored, not
hard-coded, because §10.8 puts every tunable in content.
"""

from __future__ import annotations

import math
from collections.abc import Mapping

from tracker.content.schema import ScoringProfile
from tracker.domain.types import FactorContribution, GpSensitivity

#: §9.4's factor names, in the order the table lists them. §9.10's output reads
#: contributions in this order when two tie, so it is fixed here rather than left to
#: whatever order a dict happened to be built in.
FACTOR_NAMES: tuple[str, ...] = (
    "pvp_value",
    "leverage",
    "proximity",
    "effort_decay",
    "cost_decay",
)


def kappa_for(sensitivity: GpSensitivity, profile: ScoringProfile) -> int:
    """κ for one ``gp_sensitivity`` preference (§9.6).

    κ *is* the purchase size at which cost becomes a strong negative influence, since
    ``cost_decay = exp(−gp/κ)`` is ≈0.37 at ``gp = κ``. The mapping is content (§9.7), so
    retuning *"how strongly should expensive upgrades be deprioritized"* is a YAML edit.
    """
    match sensitivity:
        case GpSensitivity.HIGH:
            return profile.kappa_gp.high
        case GpSensitivity.NORMAL:
            return profile.kappa_gp.normal
        case GpSensitivity.LOW:
            return profile.kappa_gp.low


def effort_decay(hours: float | None, profile: ScoringProfile) -> float:
    """``exp(−hours / τ)`` (§9.4), charging an unsized candidate one authored scale.

    ``hours is None`` means §8 could size neither a skill target nor a session length. It
    is charged ``profile.unknown_effort_hours`` rather than zero — see the module docstring
    and that field's own documentation for why zero is the one answer that cannot be right.

    Negative hours cannot come out of §8 and would return a value above 1, which the
    geometric mean has no clamp to catch, so the input is floored at zero.
    """
    charged = profile.unknown_effort_hours if hours is None else max(hours, 0.0)
    return math.exp(-charged / profile.tau_hours)


def cost_decay(gp: int | None, kappa: int) -> float:
    """``exp(−gp / κ)`` (§9.4), charging an unpriced candidate one κ.

    ``gp is None`` is the cost half of the gap ``hours is None`` opens, and takes the same
    answer for the same reason: one scale unit, ``exp(−1) ≈ 0.37``. It needs no profile
    field of its own because κ *is* the authored cost scale (§9.6).

    A genuinely free candidate — a refresher, whose ``gp_cost`` is 0 (§10.4) — scores
    ``1.0``, which is correct and is exactly why ``None`` must not share that value.
    """
    charged = float(kappa) if gp is None else float(max(gp, 0))
    return math.exp(-charged / kappa)


def score(
    values: Mapping[str, float], profile: ScoringProfile
) -> tuple[float, dict[str, FactorContribution]]:
    """Score one candidate from its §9.4 factor values.

    Returns the raw score and the per-factor breakdown. Both halves of each
    :class:`FactorContribution` are kept deliberately (§6.10):

    * ``value`` is the factor **as derived**, before the ε floor. A persisted ``0.0``
      records that the candidate advances nothing; a persisted ``0.01`` would record a
      tuning constant and lose the fact.
    * ``log_contribution`` is ``wᵢ · ln(max(fᵢ, ε))`` — the number that actually produced
      the ranking, and the one §9.10's reason line reads.

    A factor missing from ``values`` is an error, not a default. Scoring a candidate on
    four factors would produce a *higher* score than scoring it on five, since every term
    is ≤ 0 in log space — so an omission would look like a strength.
    """
    missing = [name for name in FACTOR_NAMES if name not in values]
    if missing:
        raise KeyError(
            f"missing §9.4 factor(s): {', '.join(missing)}. Every factor must be supplied "
            "explicitly — an omitted term raises the score, so a default would make a gap "
            "look like a strength"
        )

    weights = profile.weights
    factors: dict[str, FactorContribution] = {}
    log_score = 0.0

    for name in FACTOR_NAMES:
        value = values[name]
        weight: float = getattr(weights, name)
        contribution = weight * math.log(max(value, profile.epsilon))
        log_score += contribution
        factors[name] = FactorContribution(
            name=name, value=value, weight=weight, log_contribution=contribution
        )

    return math.exp(log_score), factors
