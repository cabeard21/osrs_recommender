"""Materializing what the pure engines computed: ``CapabilityState`` and the §6.10 snapshot.

**Why this lives in ``tracker/db/`` and not in ``tracker/progression/`` and
``tracker/recommendations/``**, where the plan's task list names it. Those two packages sit
inside §16.1's purity boundary, which Step 4 enforces mechanically: no module under
``tracker/{progression,recommendations,estimation,domain}/`` may import ``tracker.db`` or
``sqlalchemy``. A ``tracker/progression/persist.py`` cannot obey that and also write a row.
Step 9's own exit criteria require that AST test to keep passing, so one of the two had to
give and the invariant outranks the file path. The direction of dependency is the same
either way — the engines are read from, never called back into.

Everything here is a **projection of a computation**, not a fact:

* ``CapabilityState`` is overwritten on every recompute (§6.9) and can be rebuilt from
  ``PlayerState`` plus content at any time.
* ``RecommendationSnapshot`` is the deliberate exception — it accumulates, because §15's
  History view and engine debuggability both need two runs to be diffable (§6.10).
"""

from __future__ import annotations

from collections.abc import Mapping, Sequence
from dataclasses import asdict
from datetime import datetime
from typing import Any

from sqlalchemy import delete, select
from sqlalchemy.orm import Session

from tracker.db.enums import RecommendationCandidateKind
from tracker.db.models import CapabilityState, RecommendationEntry, RecommendationSnapshot
from tracker.domain.types import (
    CandidateKind,
    CapabilityView,
    Confidence,
    Consequences,
    Estimate,
    IncumbentRecommendation,
    Recommendation,
    RoadmapSelection,
)


def persist_capability_states(
    session: Session,
    player_id: int,
    views: Mapping[str, CapabilityView],
    *,
    computed_at: datetime,
) -> int:
    """Overwrite this player's ``CapabilityState`` rows from one engine run (§6.9).

    Rows for capabilities the corpus no longer declares are deleted rather than left
    behind. A stale row would keep answering "unlocked" for a capability that no longer
    exists, and §6.9's table is explicitly the materialized *output* of the current corpus
    — not a history of every capability ever authored.

    The JSON columns are written from the frozen dataclasses the engine returned, so the
    stored shape cannot drift from :class:`~tracker.domain.types.LeafRef`'s fields without
    the serialization changing with it. ``blockers`` and ``unknowns`` stay separate all the
    way to storage: §6.9 keeps them apart because they demand different user actions —
    *"do this"* against *"sync this"* — and merging them here would leave §15 no way to
    split them again.
    """
    existing = {
        row.capability_id: row
        for row in session.scalars(
            select(CapabilityState).where(CapabilityState.player_id == player_id)
        )
    }

    for capability_id, view in views.items():
        row = existing.pop(capability_id, None)
        if row is None:
            row = CapabilityState(player_id=player_id, capability_id=capability_id)
            session.add(row)

        row.status = view.status
        row.unlock_fraction = view.unlock_fraction
        row.blockers = [asdict(leaf) for leaf in view.blockers]
        row.unknowns = [asdict(leaf) for leaf in view.unknowns]
        row.readiness_confidence = view.readiness_confidence
        row.warnings = list(view.warnings)
        row.recommended_now = view.recommended_now
        row.recommended_now_reason = view.recommended_now_reason
        row.computed_at = computed_at

    for orphan in existing.values():
        session.delete(orphan)

    session.flush()
    return len(views)


def _entry_kind(kind: CandidateKind) -> RecommendationCandidateKind:
    """§6.10's axis, which is not §10.6's.

    ``CandidateKind`` says *how* a candidate changes facts; ``RecommendationCandidateKind``
    says whether the entry was authored content or synthesized from a stale practice group
    (§9.8). Only ``practice`` candidates are refreshers, and the "at most one refresher in
    the primary list" policy (G10) checks this column.
    """
    if kind is CandidateKind.PRACTICE:
        return RecommendationCandidateKind.REFRESHER
    return RecommendationCandidateKind.PROGRESSION


def _factors_json(recommendation: Recommendation) -> dict[str, dict[str, float]]:
    """§6.10 and §9.5 — raw factor values **and** their log contributions.

    Both, not either. The value is what the factor measured; the log contribution is what
    it did to the ranking, and the "Why" line is generated by reading off the largest of
    those terms (§9.5). Storing only values would leave a persisted recommendation unable
    to explain itself; storing only contributions would make it impossible to see which
    input moved between two runs.
    """
    return {
        name: {
            "value": factor.value,
            "weight": factor.weight,
            "log_contribution": factor.log_contribution,
        }
        for name, factor in recommendation.factors.items()
    }


def _consequences_json(consequences: Consequences) -> dict[str, Any]:
    """§9.10's consequences, written straight off the frozen dataclasses the engine returned.

    ``asdict`` rather than a hand-written mapping, for ``blockers``' reason: the stored shape
    then cannot drift from :class:`~tracker.domain.types.Consequences` without the
    serialization changing with it, and a field added to the derivation reaches the database
    without anyone remembering to widen a dict literal here.

    **Every id is stored beside its name**, which ``asdict`` gives for free because the
    dataclasses carry both. That is what lets the read path degrade gracefully: a capability
    the corpus has since renamed or dropped still has something truthful to render, and
    §6.10's stored ranking never depends on today's content to be legible.

    An empty :class:`Consequences` serializes to five empty lists rather than to ``{}``. Both
    read back as *nothing recorded*; the explicit shape is preferable because it distinguishes
    an entry the engine explained and found nothing for from a row written before the column
    existed.
    """
    return asdict(consequences)


def _bands_json(estimate: Estimate | None) -> list[dict[str, Any]]:
    """§8.2's per-band breakdown, for §15's "How" line.

    ``method_id`` is the field this exists for: §8.2 step 3 selects a method per band and
    every earlier version of this function discarded the answer, leaving the UI able to
    say *how long* but never *how*.

    ``fallback`` is stored beside it rather than inferred from ``method_id is None``.
    They mean the same thing today, and keeping the flag explicit is what stops a reader
    from having to know that — §8.2's conservative default is a claim the UI is required
    to qualify (§8.4), so it travels as its own field.
    """
    if estimate is None:
        return []
    return [
        {
            "from_level": band.from_level,
            "to_level": band.to_level,
            "method_id": band.method_id,
            "hours": band.hours,
            "gp": band.gp,
            "fallback": band.fallback,
        }
        for band in estimate.bands
    ]


def persist_recommendation_run(
    session: Session,
    player_id: int,
    recommendations: Sequence[Recommendation],
    *,
    selection: RoadmapSelection,
    scoring_profile_version: int,
    run_at: datetime,
    blocked: Sequence[Recommendation] = (),
) -> RecommendationSnapshot:
    """Append one §6.10 snapshot with its ranked entries.

    ``roadmap_selection`` records the weights **this run used**, which is why it is stored
    on the snapshot rather than read from ``ActiveRoadmap`` at display time: §6.12 draws
    exactly that distinction, and a History view re-reading the live setting would relabel
    every past run whenever the user reweighted their roadmaps.

    Blocked candidates are stored with ``blocked = True``. §9.4 surfaces them separately
    rather than ranking them, so their ``rank`` carries no ordering meaning; they are
    appended after the ranked entries only so the column stays a total order over the rows
    of one snapshot.
    """
    snapshot = RecommendationSnapshot(
        player_id=player_id,
        run_at=run_at,
        roadmap_selection=dict(selection.weights),
        scoring_profile_version=scoring_profile_version,
    )
    session.add(snapshot)
    session.flush()

    for rank, recommendation in enumerate([*recommendations, *blocked], start=1):
        estimate = recommendation.estimate
        session.add(
            RecommendationEntry(
                snapshot_id=snapshot.id,
                candidate_id=recommendation.candidate_id,
                rank=rank,
                candidate_kind=_entry_kind(recommendation.kind),
                score=recommendation.score,
                factors=_factors_json(recommendation),
                reason=recommendation.reason,
                estimated_hours=estimate.hours if estimate is not None else None,
                estimated_gp=estimate.gp if estimate is not None else None,
                # §6.10's column is not nullable, and LOW is the honest default: an entry
                # with no estimate at all is the least certain thing the table can hold,
                # not the most.
                estimate_confidence=estimate.confidence if estimate is not None else Confidence.LOW,
                bands=_bands_json(estimate),
                blockers=[asdict(leaf) for leaf in recommendation.blockers],
                consequences=_consequences_json(recommendation.consequences),
                blocked=recommendation.blocked,
            )
        )

    session.flush()
    return snapshot


def load_incumbent(session: Session, player_id: int) -> IncumbentRecommendation | None:
    """The previous run's top-ranked entry, for §9.9's hysteresis.

    Narrowed to the candidate id, which is all
    :class:`~tracker.domain.types.IncumbentRecommendation` carries and all §9.9 needs. The
    stored *score* is deliberately not read: §9.9 compares ``challenger.score > 1.10 ×
    incumbent.score`` with both sides scored in the **current** ranking, so reusing
    yesterday's number would let an incumbent be displaced — or defended — by drift in
    prices or a changed ``scoring_profile_version`` rather than by any challenger being
    better.

    Blocked entries are excluded: §9.9 already says an incumbent that became blocked is
    replaced outright, so one could never legitimately hold the slot.
    """
    latest = session.scalar(
        select(RecommendationSnapshot)
        .where(RecommendationSnapshot.player_id == player_id)
        .order_by(RecommendationSnapshot.run_at.desc(), RecommendationSnapshot.id.desc())
        .limit(1)
    )
    if latest is None:
        return None

    top = session.scalar(
        select(RecommendationEntry)
        .where(
            RecommendationEntry.snapshot_id == latest.id,
            RecommendationEntry.blocked.is_(False),
        )
        .order_by(RecommendationEntry.rank.asc())
        .limit(1)
    )
    if top is None:
        return None
    return IncumbentRecommendation(candidate_id=top.candidate_id)


def prune_snapshots(session: Session, player_id: int, *, keep: int) -> int:
    """Delete all but the ``keep`` most recent snapshots for one player.

    §6.10 wants runs diffable, not retained forever: the pipeline runs on every sync, so an
    untended table grows without bound for a fact whose value decays quickly. Entries
    cascade with their snapshot.
    """
    survivors = session.scalars(
        select(RecommendationSnapshot.id)
        .where(RecommendationSnapshot.player_id == player_id)
        .order_by(RecommendationSnapshot.run_at.desc(), RecommendationSnapshot.id.desc())
        .limit(keep)
    ).all()

    doomed = session.scalars(
        select(RecommendationSnapshot.id).where(
            RecommendationSnapshot.player_id == player_id,
            RecommendationSnapshot.id.not_in(survivors),
        )
    ).all()
    if not doomed:
        return 0

    session.execute(delete(RecommendationSnapshot).where(RecommendationSnapshot.id.in_(doomed)))
    session.flush()
    return len(doomed)
